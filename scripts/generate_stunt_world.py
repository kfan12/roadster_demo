STEEL = '0.16 0.17 0.2'
STEEL_GLOW = '0.02 0.07 0.30'


def curtain(x0, x1, y, h, panel=2.0):
    """Stage drape: narrow panels at alternating angles, so the folds catch
    the floodlights and read as fabric, not a wall."""
    vis, n = '', int(round((x1 - x0) / panel))
    for i in range(n):
        x = x0 + (i + 0.5) * panel
        yaw = 0.35 if i % 2 else -0.35
        vis += visual_box(f'pleat_{i}', (x, y, h / 2, 0, 0, yaw), (panel / math.cos(0.35), 0.05, h),
                          '0.20 0.012 0.018', emissive='0.035 0.0 0.004', shadows=False)
    return vis


def led_edges(length, W, t):
    """Red LED strips on both side faces of a ramp segment, at the riding
    surface (the box's +z face, towards the arc centre), in the segment frame."""
    out = ''
    for s, side in ((1, 'l'), (-1, 'r')):
        out += visual_box(f'led_{side}', (0, s * (W / 2 + 0.04), t / 2 - 0.07, 0, 0, 0),
                          (length, 0.08, 0.14), '1 0.05 0.04', emissive='1 0.04 0.03',
                          shadows=False)
    return out


def ramp_structure(R, W, t, L, arc_full):
    """Visual-only truss: a tower behind the loop, ribs from it to the arc's
    back face, and (for the 180 deg ramp) a top girder over the overhang. All
    columns stand outside the car's lane or behind the loop, but none has
    collision anyway."""
    w = 0.16
    xs = (R + t + 1.2, R + t + 2.6)  # tower columns, behind the loop
    ys = (W / 2 - 0.4, -(W / 2 - 0.4))
    top = 2 * R + t + 1.2
    vis, k = '', 0

    def add(p0, p1, glow=False):
        nonlocal vis, k
        vis += beam(f'm{k}', p0, p1, w, STEEL, STEEL_GLOW if glow else None)
        k += 1

    for x in xs:
        for y in ys:
            add((x, y, 0), (x, y, top), glow=True)
    levels = [2.0 * i for i in range(1, int(top // 2) + 1)]
    z0 = 0.0
    for z in levels:
        for y in ys:
            add((xs[0], y, z), (xs[1], y, z))
            add((xs[0], y, z0), (xs[1], y, z))  # side bracing
        for x in xs:
            add((x, ys[0], z), (x, ys[1], z))
        # rib to the arc's back face at this height, on both sides
        if z < 2 * R:
            th = math.asin(max(-1.0, min(1.0, (z - R) / (R + t))))
            xb = (R + t) * math.cos(th)
            for y in ys:
                add((xb, y, z), (xs[0], y, z))
        z0 = z
    if arc_full:
        # girder over the overhang: top chords, verticals and diagonals
        zt, zb = 2 * R + t + 1.2, 2 * R + t + 0.1
        x_end = -L
        for y in (W / 2 + 0.3, -(W / 2 + 0.3)):
            add((xs[1], y, zt), (x_end, y, zt), glow=True)
            add((R * 0.3, y, zb), (x_end, y, zb))
            n = 6
            for i in range(n + 1):
                x = x_end + (R * 0.3 - x_end) * i / n
                add((x, y, zb), (x, y, zt))
                if i < n:
                    add((x, y, zb), (x + (R * 0.3 - x_end) / n, y, zt))
    return visual_model('ramp_structure', vis)


def build_ramp(a):
    R, W, t = a.radius, a.width, a.thickness
    arc = math.radians(a.arc_deg)
    th0 = -math.pi / 2
    th1 = th0 + arc
    n = max(8, int(math.ceil(a.arc_deg / a.seg_deg)))
    d = arc / n
    # Inscribed polygon: every box's inner face is the chord between two
    # vertices ON the radius-R circle, so consecutive faces meet exactly and the
    # last vertex lands exactly on the overhang (z = 2R) and the first on the
    # ground. (Tangent-at-midpoint boxes left their ends R / cos(d/2) - R =
    # 2.7 mm outside the circle: a step onto the overhang that briefly
    # unloaded a wheel to 0.2 kN at 6 m/s.) The `overlap` extension of each box
    # lies outside the circle, behind the neighbouring face, so it adds no step.
    seg_len = 2 * R * math.sin(d / 2) + a.overlap
    links = ''
    for i in range(n):
        th = th0 + (i + 0.5) * d
        rc = R * math.cos(d / 2) + t / 2  # inner face on the chord
        x, z = rc * math.cos(th), R + rc * math.sin(th)
        pitch = math.atan2(-math.cos(th), -math.sin(th))  # box x along the arc tangent
        links += box_link(f'arc_{i:03d}', x, 0.0, z, pitch, seg_len, W, t, a.mu,
                          CONCRETE, led_edges(seg_len, W, t))
    # overhang: continues from the arc's end; for arc = 180 deg that is a flat
    # ceiling at z = 2R running in -x
    top_x, top_z = R * math.cos(th1), R + R * math.sin(th1)
    tang = (-math.sin(th1), math.cos(th1))  # direction of travel at the arc end
    outward = (math.cos(th1), math.sin(th1))  # away from the arc centre
    L = a.overhang_len
    ocx = top_x + tang[0] * L / 2 + outward[0] * t / 2
    ocz = top_z + tang[1] * L / 2 + outward[1] * t / 2
    pitch_o = math.atan2(-math.cos(th1), -math.sin(th1))
    links += box_link('overhang', ocx, 0.0, ocz, pitch_o, L + a.overlap, W, t, a.mu,
                      CONCRETE, led_edges(L + a.overlap, W, t))
    sdf = ground(300, 60, -60, 2.0)
    sdf += ramp_structure(R, W, t, L, arc_full=abs(a.arc_deg - 180.0) < 1e-6)
    # pleated red drape on the far side from the trackside camera, and light
    # towers (the camera-side one stands behind the camera)
    sdf += visual_model('backdrop', curtain(x0=-50.0, x1=20.0, y=W / 2 + 9.0, h=12.0))
    sdf += floodlights([(-32.0, 9.0, 12.0), (-8.0, 9.5, 14.0), (16.0, 7.0, 14.0),
                        (-14.0, -40.0, 12.0)], target=(-6.0, 0.0, 6.0))
    # run-in + landing road, painted to the ramp's width, ending at the ramp foot
    sdf += road_markings(-80.0, 0.0, W / 2)
    sdf += landing_zone(a.landing_x[0], a.landing_x[1], a.landing_width / 2)
    # side-on camera framing run-in, loop and landing zone (x ~ -30 .. +R)
    mid_x = (R - 30.0) / 2
    sdf += trackside_camera(eye=(mid_x, -4.2 * R, R), target=(mid_x, 0.0, R * 0.8),
                            hfov=1.1, width=640, height=400, rate=15)
    sdf += f'    <model name="ramp">\n      <static>true</static>\n{links}    </model>\n'

    big = 1e4
    surfaces = [
        plane_surface('ground', [0, 0, 0], [0, 0, 1], [-big, -big, -1.0], [big, big, R * 0.5]),
        {'type': 'arc_y', 'name': 'ramp_arc', 'center_xz': [0.0, R], 'radius': R,
         'theta0': th0, 'theta1': th1, 'y_range': [-W / 2, W / 2]},
    ]
    if abs(a.arc_deg - 180.0) < 1e-6:
        surfaces.append(plane_surface(
            'overhang', [0, 0, 2 * R], [0, 0, -1],
            [-L - 0.5, -W / 2, R], [0.5, W / 2, 2 * R + 0.5]))
    spawn = {'x': -a.run_in, 'y': 0.0, 'z': 0.05, 'roll': 0.0, 'pitch': 0.0, 'yaw': 0.0}
    geometry = {'kind': 'ramp', 'radius': R, 'arc_deg': a.arc_deg, 'width': W,
                'thickness': t, 'overhang_len': L, 'run_in': a.run_in,
                'arc_center_xz': [0.0, R], 'arc_theta': [th0, th1],
                'landing_width': a.landing_width, 'landing_x': a.landing_x,
                'drop_height': 2 * R if abs(a.arc_deg - 180.0) < 1e-6 else None}
    return sdf, surfaces, spawn, geometry


# Demo B row, in driving order (+x). Outer length x width x height [m]; parked
# side by side across the runway, so a vehicle's WIDTH lies along the path.
# The Semi (tractor) goes in the middle: the hop's arc only has to reach its
# full height near the apex, where it is highest anyway. Cybercab: estimate.
HOP_ROW = [
    ('model_3', (4.72, 1.85, 1.44), '0.75 0.1 0.1'),
    ('model_y', (4.79, 1.92, 1.62), '0.85 0.85 0.88'),
    ('semi', (6.50, 2.60, 4.10), '0.2 0.25 0.35'),
    ('cybertruck', (5.68, 2.20, 1.79), '0.62 0.64 0.66'),
    ('cybercab', (3.60, 1.90, 1.40), '0.85 0.7 0.2'),
]


def ground_surface():
    big = 1e4
    return plane_surface('ground', [0, 0, 0], [0, 0, 1], [-big, -big, -1.0], [big, big, 1.0])


def distance_marks(x0, x1, step, half_width):
    """Visual-only white bars across the road every `step` m (no collision)."""
    bars = ''
    x, i = x0, 0
    while x <= x1 + 1e-9:
        bars += f"""      <visual name="mark_{i}">
        <pose>{x:.3f} 0 0.005 0 0 0</pose>
        <cast_shadows>false</cast_shadows>
        <geometry><box><size>0.15 {2 * half_width:.3f} 0.002</size></box></geometry>
        <material><ambient>0.85 0.85 0.85 1</ambient><diffuse>0.85 0.85 0.85 1</diffuse></material>
      </visual>
"""
        x += step
        i += 1
    return f"""    <model name="distance_marks">
      <static>true</static>
      <link name="link">
{bars}      </link>
    </model>
"""


def build_launch(a):
    W, L = a.width, a.runway_len
    sdf = ground(300, 60, L / 2, 2.0)
    sdf += road_markings(-10.0, L, W / 2)
    sdf += distance_marks(0.0, L, 10.0, W / 2)
    # side-on, framing the start line to ~29 m (0-60 mph takes ~11 m)
    sdf += trackside_camera(eye=(12.0, -28.0, 2.5), target=(12.0, 0.0, 0.8),
                            hfov=1.1, width=640, height=400, rate=15)
    sdf += floodlights([(-5.0, 9.0, 12.0), (30.0, 9.0, 12.0), (12.0, -36.0, 12.0)],
                       target=(14.0, 0.0, 1.0))
    spawn = {'x': 0.0, 'y': 0.0, 'z': 0.05, 'roll': 0.0, 'pitch': 0.0, 'yaw': 0.0}
    geometry = {'kind': 'launch', 'width': W, 'runway_x': [0.0, L]}
    return sdf, [ground_surface()], spawn, geometry


def build_hop(a):
    W, gap = a.width, a.hop_gap
    links, obstacles, x = '', [], 0.0
    for name, (length, width, height), rgb in HOP_ROW:
        cx = x + width / 2
        links += box_link(name, cx, 0.0, height / 2, 0.0, width, length, height, 0.8, rgb)
        obstacles.append({'name': name, 'center': [round(cx, 4), 0.0, height / 2],
                          'size': [width, length, height]})
        x += width + gap
    row_x = [0.0, round(x - gap, 4)]
    land_x = [row_x[1] + 2.0, row_x[1] + 2.0 + a.landing_len]
    sdf = ground(300, 60, 0.0, 2.0)
    sdf += road_markings(-a.run_in - 5.0, land_x[1] + 20.0, W / 2)
    sdf += landing_zone(land_x[0], land_x[1], a.landing_width / 2)
    sdf += f'    <model name="hop_row">\n      <static>true</static>\n{links}    </model>\n'
    # side-on, framing the lift burn (~20 m before the row), the row and the
    # landing (~30 m past its start): ~54 m wide at the road
    mid_x = (row_x[0] + row_x[1]) / 2 - 1.0
    sdf += trackside_camera(eye=(mid_x, -44.0, 3.5), target=(mid_x, 0.0, 3.0),
                            hfov=1.1, width=640, height=400, rate=15)
    sdf += floodlights([(-15.0, 10.0, 12.0), (mid_x, 10.0, 14.0), (30.0, 10.0, 12.0),
                        (mid_x, -50.0, 12.0)], target=(mid_x, 0.0, 2.0))
    spawn = {'x': -a.run_in, 'y': 0.0, 'z': 0.05, 'roll': 0.0, 'pitch': 0.0, 'yaw': 0.0}
    geometry = {'kind': 'hop', 'width': W, 'obstacles': obstacles, 'row_x': row_x,
                'run_in': a.run_in, 'landing_width': a.landing_width, 'landing_x': land_x}
    return sdf, [ground_surface()], spawn, geometry


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--kind', choices=('ceiling', 'ramp', 'launch', 'hop'), required=True)
    ap.add_argument('--out', default=None, help='world name (default roadster_<kind>)')
    ap.add_argument('--width', type=float, default=5.0)
    ap.add_argument('--thickness', type=float, default=0.4)
    ap.add_argument('--mu', type=float, default=1.5, help='ramp/ceiling friction (tire mu binds)')
    # ceiling
    ap.add_argument('--height', type=float, default=6.0)
    ap.add_argument('--slab-len', type=float, default=20.0)
    # ramp
    ap.add_argument('--radius', type=float, default=8.0)
    ap.add_argument('--arc-deg', type=float, default=180.0)
    ap.add_argument('--seg-deg', type=float, default=3.0, help='box-chain segment angle')
    ap.add_argument('--overlap', type=float, default=0.02, help='segment length overlap [m]')
    ap.add_argument('--overhang-len', type=float, default=5.0,
                    help='just past the top: room for the car (4.5 m) to stop and hold')
    ap.add_argument('--run-in', type=float, default=None,
                    help='spawn distance before the ramp (25) or the hop row (60)')
    ap.add_argument('--landing-width', type=float, default=12.0,
                    help='landing zone width, centred on the road [m]')
    ap.add_argument('--landing-x', type=float, nargs=2, default=[-45.0, -12.0],
                    help='ramp landing zone x range: touchdown ~-22 m, rollout to ~-35 m')
    # launch
    ap.add_argument('--runway-len', type=float, default=120.0, help='launch runway length [m]')
    # hop
    ap.add_argument('--hop-gap', type=float, default=0.5, help='gap between parked vehicles [m]')
    ap.add_argument('--landing-len', type=float, default=45.0,
                    help='hop landing zone length past the row [m]')
    a = ap.parse_args()
    if a.run_in is None:
        a.run_in = 60.0 if a.kind == 'hop' else 25.0
    name = a.out or f'roadster_{a.kind}'

    builders = {'ceiling': build_ceiling, 'ramp': build_ramp, 'launch': build_launch,
                'hop': build_hop}
    sdf, surfaces, spawn, geometry = builders[a.kind](a)
    cli = ' '.join(f'--{k.replace("_", "-")} ' + (' '.join(map(str, v)) if isinstance(v, list) else str(v))
                   for k, v in vars(a).items() if v is not None)
    WORLD_DIR.mkdir(parents=True, exist_ok=True)
    MAP_DIR.mkdir(parents=True, exist_ok=True)
    look = DAY  # test rigs
    if a.kind != 'ceiling':  # the demo scenes
        cam = re.search(r'<model name="trackside_camera">\s*<static>true</static>\s*'
                        r'<pose>([^<]+)</pose>', sdf)
        look = NIGHT + night_gui(cam.group(1) if cam else '-6 0 6 0 0.5 0')
    (WORLD_DIR / f'{name}.world.sdf').write_text(HEADER.format(name=name, args=cli) + look + sdf + FOOTER)
    (MAP_DIR / f'{name}.json').write_text(json.dumps(
        {'world': name, 'generator': f'generate_stunt_world.py {cli}', 'spawn': spawn,
         'geometry': geometry, 'surfaces': surfaces}, indent=2) + '\n')
    print(f'wrote {WORLD_DIR / (name + ".world.sdf")} and {MAP_DIR / (name + ".json")}')


if __name__ == '__main__':
    main()
