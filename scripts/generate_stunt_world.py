#!/usr/bin/env python3
"""generate_stunt_world.py - roadster stunt worlds + their analytic surfaces.

Writes a Gazebo Fortress world and maps/<name>.json, the single source of the
geometry: the world is built from the same numbers the JSON records, and the
JSON is what the actuation system's fan reads for its surface gap (Fortress has
no ray queries) and what the stunt controller reads for ramp-frame tracking.

Kinds:
  ceiling  flat ground + a horizontal slab overhead (fan inverted-hold test)
  ramp     run-in road -> circular quarter-pipe arc of radius R continuing to
           `arc_deg` (180 = fully inverted) -> horizontal overhang back over
           the run-in, so a car flying off its end lands on flat road

Ramp frame (x forward along the run-in, z up): the arc's centre is (0, R), so
its bottom is tangent to the ground at x = 0 and an inverted car at the top
(z = 2R) travels in -x onto the overhang. The overhang must extend far enough
in -x for the car to stop on it, hold, then accelerate forward upside down and
fly off its far end over flat road; --overhang-len defaults to 25 m for that.

Usage:
  python3 scripts/generate_stunt_world.py --kind ceiling --height 6
  python3 scripts/generate_stunt_world.py --kind ramp --radius 8
Outputs:
  src/roadster_description/worlds/<name>.world.sdf
  maps/<name>.json
"""
import argparse
import json
import math
from pathlib import Path

WS = Path(__file__).resolve().parents[1]
WORLD_DIR = WS / 'src' / 'roadster_description' / 'worlds'
MAP_DIR = WS / 'maps'

HEADER = """<?xml version="1.0" ?>
<!-- GENERATED by scripts/generate_stunt_world.py {args} - do not hand-edit;
     geometry is mirrored in maps/{name}.json (the fan's analytic surfaces). -->
<sdf version="1.8">
  <world name="{name}">
    <physics name="1ms" type="dart">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="ignition-gazebo-physics-system"
            name="ignition::gazebo::systems::Physics">
      <engine><filename>ignition-physics-dartsim-plugin</filename></engine>
    </plugin>
    <plugin filename="ignition-gazebo-user-commands-system"
            name="ignition::gazebo::systems::UserCommands"/>
    <plugin filename="ignition-gazebo-scene-broadcaster-system"
            name="ignition::gazebo::systems::SceneBroadcaster"/>
    <plugin filename="ignition-gazebo-imu-system"
            name="ignition::gazebo::systems::Imu"/>
    <plugin filename="ignition-gazebo-forcetorque-system"
            name="ignition::gazebo::systems::ForceTorque"/>
    <plugin filename="ignition-gazebo-contact-system"
            name="ignition::gazebo::systems::Contact"/>
    <gravity>0 0 -9.81</gravity>
    <light type="directional" name="sun">
      <cast_shadows>false</cast_shadows>
      <pose>0 0 50 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse>
      <direction>-0.4 0.2 -0.9</direction>
    </light>
"""

FOOTER = """  </world>
</sdf>
"""


def surface_block(mu):
    return (f'<surface><friction><ode><mu>{mu}</mu><mu2>{mu}</mu2></ode></friction>'
            '<contact><ode><min_depth>0.001</min_depth></ode></contact></surface>')


def ground(size_x, size_y, cx, mu):
    return f"""    <model name="ground">
      <static>true</static>
      <pose>{cx:.3f} 0 0 0 0 0</pose>
      <link name="link">
        <collision name="collision">
          <geometry><plane><normal>0 0 1</normal><size>{size_x} {size_y}</size></plane></geometry>
          {surface_block(mu)}
        </collision>
        <visual name="visual">
          <geometry><plane><normal>0 0 1</normal><size>{size_x} {size_y}</size></plane></geometry>
          <material><ambient>0.25 0.25 0.27 1</ambient><diffuse>0.25 0.25 0.27 1</diffuse></material>
        </visual>
      </link>
    </model>
"""


def box_link(name, x, y, z, pitch, sx, sy, sz, mu, rgb):
    return f"""      <link name="{name}">
        <pose>{x:.4f} {y:.4f} {z:.4f} 0 {pitch:.6f} 0</pose>
        <collision name="c">
          <geometry><box><size>{sx:.4f} {sy:.4f} {sz:.4f}</size></box></geometry>
          {surface_block(mu)}
        </collision>
        <visual name="v">
          <geometry><box><size>{sx:.4f} {sy:.4f} {sz:.4f}</size></box></geometry>
          <material><ambient>{rgb} 1</ambient><diffuse>{rgb} 1</diffuse></material>
        </visual>
      </link>
"""


def plane_surface(name, point, normal, box_min, box_max):
    return {'type': 'plane', 'name': name, 'point': point, 'normal': normal,
            'box_min': box_min, 'box_max': box_max}


def build_ceiling(a):
    h, half_len, half_w, t = a.height, a.slab_len / 2, a.width / 2, a.thickness
    links = box_link('slab', 0.0, 0.0, h + t / 2, 0.0, 2 * half_len, 2 * half_w, t,
                     a.mu, '0.55 0.55 0.6')
    sdf = ground(200, 60, 0, 2.0)
    sdf += f'    <model name="ceiling">\n      <static>true</static>\n{links}    </model>\n'
    big = 1e4
    surfaces = [
        plane_surface('ground', [0, 0, 0], [0, 0, 1], [-big, -big, -1.0], [big, big, h / 2]),
        plane_surface('ceiling', [0, 0, h], [0, 0, -1],
                      [-half_len, -half_w, h / 2], [half_len, half_w, h + 0.5]),
    ]
    # inverted car: base_link (wheel-contact level) just under the slab, roll = pi
    spawn = {'x': 0.0, 'y': 0.0, 'z': h - 0.01, 'roll': math.pi, 'pitch': 0.0, 'yaw': 0.0}
    geometry = {'kind': 'ceiling', 'height': h, 'slab_len': a.slab_len, 'width': a.width}
    return sdf, surfaces, spawn, geometry


def build_ramp(a):
    R, W, t = a.radius, a.width, a.thickness
    arc = math.radians(a.arc_deg)
    th0 = -math.pi / 2
    th1 = th0 + arc
    n = max(8, int(math.ceil(a.arc_deg / a.seg_deg)))
    d = arc / n
    # Inscribed polygon: every box's inner face is the chord between two
    # vertices ON the radius-R circle, so consecutive faces meet exactly and the
    # last vertex lands exactly on the overhang (z = 2R) and the first on the
    # ground. (Tangent-at-midpoint boxes left their ends R / cos(d/2) - R =
    # 2.7 mm outside the circle: a step onto the overhang that briefly
    # unloaded a wheel to 0.2 kN at 6 m/s.) The `overlap` extension of each box
    # lies outside the circle, behind the neighbouring face, so it adds no step.
    seg_len = 2 * R * math.sin(d / 2) + a.overlap
    links = ''
    for i in range(n):
        th = th0 + (i + 0.5) * d
        rc = R * math.cos(d / 2) + t / 2  # inner face on the chord
        x, z = rc * math.cos(th), R + rc * math.sin(th)
        pitch = math.atan2(-math.cos(th), -math.sin(th))  # box x along the arc tangent
        shade = 0.45 + 0.15 * (i % 2)
        links += box_link(f'arc_{i:03d}', x, 0.0, z, pitch, seg_len, W, t, a.mu,
                          f'{shade:.2f} {shade:.2f} {shade + 0.05:.2f}')
    # overhang: continues from the arc's end; for arc = 180 deg that is a flat
    # ceiling at z = 2R running in -x
    top_x, top_z = R * math.cos(th1), R + R * math.sin(th1)
    tang = (-math.sin(th1), math.cos(th1))  # direction of travel at the arc end
    outward = (math.cos(th1), math.sin(th1))  # away from the arc centre
    L = a.overhang_len
    ocx = top_x + tang[0] * L / 2 + outward[0] * t / 2
    ocz = top_z + tang[1] * L / 2 + outward[1] * t / 2
    pitch_o = math.atan2(-math.cos(th1), -math.sin(th1))
    links += box_link('overhang', ocx, 0.0, ocz, pitch_o, L + a.overlap, W, t, a.mu,
                      '0.55 0.45 0.45')
    sdf = ground(300, 60, -60, 2.0)
    sdf += f'    <model name="ramp">\n      <static>true</static>\n{links}    </model>\n'

    big = 1e4
    surfaces = [
        plane_surface('ground', [0, 0, 0], [0, 0, 1], [-big, -big, -1.0], [big, big, R * 0.5]),
        {'type': 'arc_y', 'name': 'ramp_arc', 'center_xz': [0.0, R], 'radius': R,
         'theta0': th0, 'theta1': th1, 'y_range': [-W / 2, W / 2]},
    ]
    if abs(a.arc_deg - 180.0) < 1e-6:
        surfaces.append(plane_surface(
            'overhang', [0, 0, 2 * R], [0, 0, -1],
            [-L - 0.5, -W / 2, R], [0.5, W / 2, 2 * R + 0.5]))
    spawn = {'x': -a.run_in, 'y': 0.0, 'z': 0.05, 'roll': 0.0, 'pitch': 0.0, 'yaw': 0.0}
    geometry = {'kind': 'ramp', 'radius': R, 'arc_deg': a.arc_deg, 'width': W,
                'thickness': t, 'overhang_len': L, 'run_in': a.run_in,
                'arc_center_xz': [0.0, R], 'arc_theta': [th0, th1],
                'drop_height': 2 * R if abs(a.arc_deg - 180.0) < 1e-6 else None}
    return sdf, surfaces, spawn, geometry


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--kind', choices=('ceiling', 'ramp'), required=True)
    ap.add_argument('--out', default=None, help='world name (default roadster_<kind>)')
    ap.add_argument('--width', type=float, default=5.0)
    ap.add_argument('--thickness', type=float, default=0.4)
    ap.add_argument('--mu', type=float, default=1.5, help='ramp/ceiling friction (tire mu binds)')
    # ceiling
    ap.add_argument('--height', type=float, default=6.0)
    ap.add_argument('--slab-len', type=float, default=20.0)
    # ramp
    ap.add_argument('--radius', type=float, default=8.0)
    ap.add_argument('--arc-deg', type=float, default=180.0)
    ap.add_argument('--seg-deg', type=float, default=3.0, help='box-chain segment angle')
    ap.add_argument('--overlap', type=float, default=0.02, help='segment length overlap [m]')
    ap.add_argument('--overhang-len', type=float, default=25.0,
                    help='room to stop, hold, then drive off upside down and launch')
    ap.add_argument('--run-in', type=float, default=25.0, help='spawn distance before the ramp')
    a = ap.parse_args()
    name = a.out or f'roadster_{a.kind}'

    sdf, surfaces, spawn, geometry = (build_ceiling if a.kind == 'ceiling' else build_ramp)(a)
    cli = ' '.join(f'--{k.replace("_", "-")} {v}' for k, v in vars(a).items() if v is not None)
    WORLD_DIR.mkdir(parents=True, exist_ok=True)
    MAP_DIR.mkdir(parents=True, exist_ok=True)
    (WORLD_DIR / f'{name}.world.sdf').write_text(HEADER.format(name=name, args=cli) + sdf + FOOTER)
    (MAP_DIR / f'{name}.json').write_text(json.dumps(
        {'world': name, 'generator': f'generate_stunt_world.py {cli}', 'spawn': spawn,
         'geometry': geometry, 'surfaces': surfaces}, indent=2) + '\n')
    print(f'wrote {WORLD_DIR / (name + ".world.sdf")} and {MAP_DIR / (name + ".json")}')


if __name__ == '__main__':
    main()
