def plane_surface(name, point, normal, box_min, box_max):
    return {'type': 'plane', 'name': name, 'point': point, 'normal': normal,
            'box_min': box_min, 'box_max': box_max}


def build_ceiling(a):
    h, half_len, half_w, t = a.height, a.slab_len / 2, a.width / 2, a.thickness
    links = box_link('slab', 0.0, 0.0, h + t / 2, 0.0, 2 * half_len, 2 * half_w, t,
                     a.mu, '0.55 0.55 0.6')
    sdf = ground(200, 60, 0, 2.0)
    sdf += f'    <model name="ceiling">\n      <static>true</static>\n{links}    </model>\n'
    big = 1e4
    surfaces = [
        plane_surface('ground', [0, 0, 0], [0, 0, 1], [-big, -big, -1.0], [big, big, h / 2]),
        plane_surface('ceiling', [0, 0, h], [0, 0, -1],
                      [-half_len, -half_w, h / 2], [half_len, half_w, h + 0.5]),
    ]
    # inverted car: base_link (wheel-contact level) just under the slab, roll = pi
    spawn = {'x': 0.0, 'y': 0.0, 'z': h - 0.01, 'roll': math.pi, 'pitch': 0.0, 'yaw': 0.0}
    geometry = {'kind': 'ceiling', 'height': h, 'slab_len': a.slab_len, 'width': a.width}
    return sdf, surfaces, spawn, geometry


# The event ramp: smooth light-grey concrete with red LED strips along both
